#!/usr/bin/env python3
"""Finish an already running first-use experiment, then measure fresh cached use.

This small supervisor never restarts a failed/guard-stopped first-use worker. It
waits for durable terminal metadata, verifies evidence and runs the cached command
only on success. Results stay explicitly partial if any stage fails.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import subprocess
import time

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--go', required=True)
a = p.parse_args()
summary = {'status': 'waiting-for-first-use', 'supervisor_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}


def save():
    (HERE / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')


def run(*args):
    subprocess.run(args, cwd=ROOT, check=True)


save()
try:
    while True:
        record = json.loads((HERE / 'initial/results.json').read_text())
        if record['status'] not in ['running', 'finalizing']:
            break
        time.sleep(15)
    run('python3', str(HERE / 'analyze.py'), 'initial')
    summary['first_use'] = json.loads((HERE / 'initial/analysis.json').read_text())
    if record['status'] != 'passed':
        raise RuntimeError('first use incomplete; cached encoding not started')
    if (HERE / 'cached').exists():
        raise RuntimeError('cached output already exists; refusing to overwrite it')
    summary['status'] = 'measuring-fresh-cached'; save()
    run('python3', str(HERE / 'run.py'), '--go', a.go, '--run-name', 'cached', '--online-only')
    run('python3', str(HERE / 'analyze.py'), 'cached')
    summary['cached'] = json.loads((HERE / 'cached/analysis.json').read_text())
    assert summary['cached']['first_use_word_match']
    summary['status'] = 'passed'
except Exception as error:
    summary.update(status='incomplete', error=repr(error))
summary['finished_utc'] = datetime.now(timezone.utc).isoformat()
save()
lines = ['# Local s=15 run outcome', '', 'Generated by [finish.py](finish.py); exact provenance and outcomes are in [summary.json](summary.json).', '', f"Status: **{summary['status']}**.", '']
if summary['status'] == 'passed':
    first, cached = summary['first_use'], summary['cached']
    lines += [f"Exact K={first['k']:,}, N={first['n']:,}; code rate {first['code_rate']:.6f}.", '', '| Measurement | First-use process | Fresh cached process |', '| --- | ---: | ---: |', f"| Median encoding, seconds | {first['median_encoding_s']:.3f} | {cached['median_encoding_s']:.3f} |", f"| Whole-process peak RSS, GiB | {first['peak_process_rss_gib']:.3f} | {cached['peak_process_rss_gib']:.3f} |", '', 'Full systematic checks, sampled curves, repeated word hashes and packed readback pass. Fresh cached output matches first use. Preparation includes diagnostic GC/profiling; encoding timings are profiled. These results validate this experimental standalone path, not the full application wrapper or production security.']
else:
    lines += [summary.get('error', 'Incomplete.'), '', 'No successful large encoding capability is claimed. Completed cache stages and available profiles remain retained.']
lines += ['', 'See [method and limitations](report.md), [first-use metadata](initial/results.json) and their linked evidence.']
(HERE / 'summary.md').write_text('\n'.join(lines) + '\n')
# Record the asynchronous outcome in the same board used to start this work item.
now = datetime.now(timezone.utc)
name = now.strftime('%Y-%m-%d-%H%M') + '-codex-scale-008-results.md'
(ROOT / 'message-board' / name).write_text(f"# SCALE-008 results\n\nTimestamp: {now.isoformat()}. Agent: Codex experiment supervisor.\n\nThe local run finished with status **{summary['status']}**. See the [generated outcome](../experiments/parallel-s15/summary.md), [exact evidence](../experiments/parallel-s15/summary.json) and [method/report](../experiments/parallel-s15/report.md). Source and artifact checks are performed by analyze.py. Completed cache stages/profiles remain retained. No production or application-integration claim is added. README was checked and linked to this experiment before launch; this supervisor does not silently change project capability claims. Full Go/native suites, focused race/vet and smoke/fresh-cache checks passed before launch. Review the measured outcome and update current-status documentation before publishing new performance/capacity claims.\n")
with (ROOT / 'message-board/README.md').open('a') as f:
    f.write(f'| {now:%Y-%m-%d %H:%M} | SCALE-008 | Results | [Local s15 run outcome]({name}) |\n')
print('s15 supervisor ' + summary['status'], flush=True)
